/** **굵게** 표기를 TextRun으로 */
const runs = (text, o = {}) =>
  text.split(/(\*\*[^*]+\*\*|`[^`]+`)/).filter(Boolean).map((t) => {
    if (t.startsWith('**')) return new TextRun({ text: t.slice(2, -2), bold: true, font: FONT, ...o })
    if (t.startsWith('`')) return new TextRun({ text: t.slice(1, -1), font: 'Consolas', size: 19, shading: { type: ShadingType.CLEAR, fill: GRAY }, ...o })
    return new TextRun({ text: t, font: FONT, ...o })
  })

const H1 = (t) => new Paragraph({ heading: HeadingLevel.HEADING_1, pageBreakBefore: true, numbering: { reference: 'head', level: 0 }, children: [new TextRun({ text: t, font: FONT })] })
const H2 = (t, nonum) => new Paragraph({ heading: HeadingLevel.HEADING_2, numbering: nonum ? undefined : { reference: 'head', level: 1 }, children: [new TextRun({ text: t, font: FONT })] })
const H3 = (t) => new Paragraph({ heading: HeadingLevel.HEADING_3, numbering: { reference: 'head', level: 2 }, children: [new TextRun({ text: t, font: FONT })] })
const P = (t, o = {}) => new Paragraph({ spacing: { after: 100, line: 300 }, children: runs(t), ...o })
const B = (t, lvl = 0) => new Paragraph({ numbering: { reference: 'bul', level: lvl }, spacing: { after: 40, line: 290 }, children: runs(t) })
let stepRef = 0
const steps = (items) => {
  stepRef += 1
  return items.map((t) => new Paragraph({ numbering: { reference: 'num' + stepRef, level: 0 }, spacing: { after: 40, line: 290 }, children: runs(t) }))
}
