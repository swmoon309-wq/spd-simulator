/** 용어를 이름·약어·설명에서 찾는다(대소문자 무시, 공백으로 나눈 낱말이 모두 들어 있어야 한다). */
export function searchGlossary(query: string, terms: Term[] = GLOSSARY): Term[] {
  const words = query
    .toLowerCase()
    .split(/\s+/)
    .filter((w) => w !== '')
  if (words.length === 0) return terms
  return terms.filter((t) => {
    const hay = `${t.term} ${t.alias ?? ''} ${t.meaning}`.toLowerCase()
    return words.every((w) => hay.includes(w))
  })
}

