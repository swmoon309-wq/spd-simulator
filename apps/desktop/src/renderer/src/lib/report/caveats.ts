/** 모델별 한계 문구. 모델의 사실(검증 여부, 가정한 값)만 적는다. */
export function modelCaveat(entry: ModelEntry): string {
  if (entry.id === 'brooks') return 'Brooks 법칙 모델은 책 1.4의 수치(숙련 20명 고정, 약 274일)와 일치함을 확인한 모델입니다. 인원 추가의 효과는 모델의 판단 시점·오버헤드 가정을 따릅니다.'
  if (entry.id === 'integrated-project') return '통합 프로젝트 모델(4섹터 단순판)은 책의 수치와 정량적으로 일치하지 않고 보정되지 않았습니다. 일부 파라미터는 책에 값이 없어 가정한 값이므로 결과는 정성적으로 읽으세요.'
  if (entry.id === 'integrated-project-ai') return '통합 프로젝트 + AI 보조 모델은 통합 프로젝트 모델(보정되지 않음)에 AI의 생성 가속을 더한 확장입니다. AI 항목의 값(적용 비율, 숙련자·신입별 가속, 반복 오버헤드, 검토 노력·용량·검증 숙련도, 오류 밀도)은 문헌마다 크게 달라 기본값을 정하지 않았고, 조직 자료로 보정되지 않았습니다. 검토 깊이가 혼잡에 따라 얕아지는 곡선의 모양과 규모에 따라 QA 검출 효율이 떨어지는 지수는 가정입니다. 이 모델은 시험에서 발견한 오류의 처리가 QA 검출과 재작업보다 싸다고 두므로, 후기 발견 비용 배수를 올리지 않으면 검출 효율이 떨어질수록 일정이 오히려 줄어 보입니다. 기술 부채의 영향 곡선(생산성·오류 배수)의 모양과 부채 발생·상환의 크기도 가정이며, 부채는 태스크 환산 점수라 조직의 정적 분석 지표와 직접 연결되지 않습니다. 계획이 믿는 생성 가속은 개발 생산성에만 적용하며, 인원을 고정하면 낙관적인 계획이 일정 압박을 높여 일정은 줄고 오류와 소진이 느는 기존 모델의 되먹임이 나타납니다. 비용 층(맨데이 단가, 토큰 비용, 이용료·인프라)은 입력한 단가를 곱해 금액으로 바꿀 뿐 일정·품질 동역학에 영향을 주지 않으며, 토큰 비용은 반복 오버헤드를 재시도 횟수의 대리로 쓰는 단순한 가정입니다. 단가는 조직이 정해야 하는 값이므로 결과를 AI 효과의 예측이 아니라 가정한 가속과 단가가 일정·공수·금액에 미치는 영향으로 읽으세요.'
  if (entry.category === 'structure') return `${entry.title}은(는) 책 3장의 구조를 하나만 보이는 학습용 모델입니다. 기본값은 구조의 특징을 보기 좋게 고른 값이며 실제 프로젝트에 보정한 값이 아닙니다.`
  if (entry.category === 'user') {
    const basedOn = entry.custom?.doc.info.basedOn
    return `'${entry.title}'(버전 ${entry.def.meta.version})은(는) 사용자가 만들었거나 가져온 모델입니다${basedOn ? `(원본: ${basedOn})` : ''}. 보정·검증되지 않았을 수 있으며, 편집기를 통과했다고 현실에 맞는 모델이라는 뜻은 아닙니다. 구조 점검과 실제 데이터와의 비교 결과를 함께 확인하세요.${unitNote(entry) ? ` 이 모델에는 ${unitNote(entry)}이 있습니다(단위가 맞지 않는 수식이 있어 결과를 읽을 때 주의하세요).` : ''}`
  }
  return '이 모델은 보정·검증 여부가 확인되지 않았습니다. 사용하기 전에 구조 점검과 실제 데이터와의 비교를 해 보세요.'
}
